import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
from backend_actions import ActionSpec

CONTROLS = json.loads((Path(__file__).resolve().parents[1]/'config/liquid-glass.json').read_text())
DEFAULTS = {key: item['default'] for key, item in CONTROLS.items()}
MARKER = '// Generated by LME Shell: liquid glass backdrop blur.\n'
RETIRED = {'blur', 'blurPreset', 'appliedBlur'}
MIN_NIRI = (26, 4)
# Blur-region rules mirroring the blur section of config/niri/lme-shell.kdl (keep in sync;
# tests/test_glass_blur.py checks the match).
_RULES = """layer-rule {
    match namespace="^lme-(bar|overlay|authentication|desktop|notifications|osd)$"
    background-effect {
        xray false
    }
}
window-rule {
    match app-id="^lme-shell-settings$"
    // Keep niri's focus-ring backing from filling the transparent window.
    draw-border-with-background false
    background-effect {
        xray false
    }
}
"""


def probe_niri_version():
    """Return (major, minor) for the installed niri, or None if unavailable.

    Kept as a module-level function so tests can patch it; apply_blur calls
    it directly (never through the backend runner).
    """
    try:
        result = subprocess.run(['niri', '--version'], capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.SubprocessError):
        return None
    match = re.search(r'\b(\d+)\.(\d+)\b', result.stdout or '')
    return tuple(map(int, match.groups())) if match else None


def snippet(values):
    """Render the generated KDL for compositor blur (xray false)."""
    values = validate(values)
    return (MARKER + '// Include AFTER generic background-effect rules; later rules win.\n'
            + _RULES
            + f"blur {{\n    passes {values['passes']}\n    offset {values['offset']:.1f}\n}}\n")


def validate(value, partial=False):
    if not isinstance(value, dict):
        raise ValueError('Unknown Liquid glass setting')
    if not set(value) <= CONTROLS.keys() | RETIRED:
        raise ValueError('Unknown Liquid glass setting')
    result = {} if partial else dict(DEFAULTS)
    for key, number in value.items():
        if key in RETIRED:
            continue
        item = CONTROLS[key]
        if key == 'tint':
            if not isinstance(number, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?', number):
                raise ValueError('Glass tint must be #RRGGBB or #AARRGGBB')
        elif type(number) not in (int, float) or not item['min'] <= number <= item['max'] or key == 'passes' and number != int(number):
            raise ValueError('Invalid Liquid glass setting: '+key)
        result[key] = number.lower() if key == 'tint' else int(number) if key == 'passes' else float(number)
    return result


def apply_blur(folder, values):
    values = validate(values)
    detected = probe_niri_version()
    if detected is None or detected < MIN_NIRI:
        found = f'niri {detected[0]}.{detected[1]}' if detected else 'no detectable niri'
        raise ValueError(f'Compositor blur needs niri 26.04+; found {found}. The snippet was not written.')
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True, mode=0o700)
    path = folder/'liquid-blur.kdl'
    if path.is_symlink() or path.exists() and (not path.is_file() or not path.read_text().startswith(MARKER)):
        raise ValueError('Refusing to replace a user-owned liquid-blur.kdl. Move it before applying.')
    content = snippet(values)
    fd, temporary = tempfile.mkstemp(dir=folder, prefix='.liquid-blur-')
    try:
        with os.fdopen(fd, 'w') as handle:
            handle.write(content)
            handle.flush(); os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary): os.unlink(temporary)
    return f'Saved {path}. Deploy includes it automatically; manual users include it after lme-shell.kdl, then validate. Included files reload when applied. This changes compositor-wide blur.'


def provide_blur(folder, values):
    def apply(request):
        return apply_blur(folder(), values())
    return (ActionSpec('glassBlurApply', {'shell','settings'}, apply, lambda request:None),), lambda:{}
