import colorsys
import re
from desktop_features import validate_palette

HEX = re.compile(r'#[0-9a-fA-F]{6}\Z')
HEADER = '# Generated by lme-shell (palette sink). Do not edit; source: LME Shell settings.'
DERIVED = {'primaryContainer': ('panel', 'accent', 0.30), 'secondaryContainer': ('panel', 'pink', 0.22),
           'tertiaryContainer': ('panel', 'cyan', 0.19), 'surfaceContainer': ('background', 'surface', 0.66),
           'surfaceContainerHigh': ('panel', 'surface', 0.74)}
HUE_KEYS = ('red', 'green', 'yellow', 'purple', 'pink', 'cyan')
ORDER = ('background', 'foreground', 'cursor', 'selection_background', 'selection_foreground') + \
        tuple('color%d' % index for index in range(16))


def hex_to_rgb(value):
    if not isinstance(value, str) or HEX.fullmatch(value) is None:
        raise ValueError('Invalid hex color: ' + str(value))
    return tuple(int(value[index:index + 2], 16) / 255 for index in (1, 3, 5))


def rgb_to_hex(rgb):
    return '#' + ''.join('%02x' % int(round(max(0.0, min(1.0, channel)) * 255)) for channel in rgb)


def mix(first, second, amount):
    a, b = hex_to_rgb(first), hex_to_rgb(second)
    return rgb_to_hex(tuple(x * (1 - amount) + y * amount for x, y in zip(a, b)))


def relative_luminance(value):
    def linear(channel):
        return channel / 12.92 if channel <= 0.04045 else ((channel + 0.055) / 1.055) ** 2.4
    red, green, blue = hex_to_rgb(value)
    return 0.2126 * linear(red) + 0.7152 * linear(green) + 0.0722 * linear(blue)


def contrast_ratio(first, second):
    high, low = sorted((relative_luminance(first), relative_luminance(second)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def ensure_contrast(fg_hex, bg_hex, minimum):
    if contrast_ratio(fg_hex, bg_hex) >= minimum:
        return fg_hex.lower(), False
    hue, lightness, saturation = colorsys.rgb_to_hls(*hex_to_rgb(fg_hex))
    step = 0.02 if relative_luminance(fg_hex) > relative_luminance(bg_hex) else -0.02
    for _ in range(30):
        lightness = min(1.0, max(0.0, lightness + step))
        candidate = rgb_to_hex(colorsys.hls_to_rgb(hue, lightness, saturation))
        if contrast_ratio(candidate, bg_hex) >= minimum:
            return candidate, True
    return ('#ffffff' if relative_luminance(bg_hex) < 0.5 else '#0a0a0a'), True


def _is_hex(value):
    return isinstance(value, str) and HEX.fullmatch(value) is not None


def _derive(colors):
    for role, sources in DERIVED.items():
        if _is_hex(colors.get(role)):
            continue
        first, second, amount = sources
        if _is_hex(colors.get(first)) and _is_hex(colors.get(second)):
            colors[role] = mix(colors[first], colors[second], amount)
    if not _is_hex(colors.get('onPrimary')) and _is_hex(colors.get('background')):
        colors['onPrimary'] = colors['background']


def effective_palette(prefs: dict, catalog: list) -> dict:
    source = prefs.get('paletteSource')
    if source == 'preset':
        entry = next((item for item in catalog if item.get('id') == prefs.get('palettePreset')), None)
        if entry is None or not isinstance(entry.get('colors'), dict):
            raise ValueError('Unknown palette preset')
        colors = dict(entry['colors'])
    elif source == 'wallpaper':
        colors = dict(prefs.get('wallpaperPalette') or {})
        if not colors:
            return {'unsupported': 'empty-wallpaper-palette'}
        colors = validate_palette(colors)
    else:
        return {'unsupported': 'dracula-literals-live-in-qml'}
    _derive(colors)
    return {key: value.lower() if isinstance(value, str) else value for key, value in colors.items()}


def _require(palette, key):
    value = palette.get(key)
    if not _is_hex(value):
        raise ValueError('Palette is missing ' + key)
    return value.lower()


def _emphasize(value, background):
    hue, lightness, saturation = colorsys.rgb_to_hls(*hex_to_rgb(value))
    shift = 0.08 if relative_luminance(background) < 0.5 else -0.08
    return rgb_to_hex(colorsys.hls_to_rgb(hue, min(1.0, max(0.0, lightness + shift)), saturation))


def render_details(palette: dict) -> dict:
    background = _require(palette, 'background')
    text = _require(palette, 'text')
    accent = _require(palette, 'accent')
    foreground, adjusted = ensure_contrast(text, background, 4.5)
    cursor = accent if contrast_ratio(accent, background) >= 4.5 else foreground
    selection = palette.get('secondaryContainer')
    if not _is_hex(selection):
        selection = mix(palette['panel'], palette['pink'], 0.22) \
            if _is_hex(palette.get('panel')) and _is_hex(palette.get('pink')) else None
    if selection is None:
        raise ValueError('Palette is missing secondaryContainer')
    selection = selection.lower()
    selection_foreground, changed = ensure_contrast(background, selection, 4.5)
    adjusted = adjusted or changed
    colors = {'background': background, 'foreground': foreground, 'cursor': cursor,
              'selection_background': selection, 'selection_foreground': selection_foreground,
              'color0': mix(background, accent, 0.06)}
    for index, key in enumerate(HUE_KEYS, start=1):
        value, changed = ensure_contrast(_require(palette, key), background, 3.0)
        colors['color%d' % index] = value
        adjusted = adjusted or changed
    color7, changed = ensure_contrast(mix(text, background, 0.10), background, 4.5)
    adjusted = adjusted or changed
    color8, changed = ensure_contrast(mix(background, text, 0.45), background, 3.0)
    adjusted = adjusted or changed
    color15, changed = ensure_contrast(mix(background, text, 0.90), background, 4.5)
    adjusted = adjusted or changed
    colors.update({'color7': color7, 'color8': color8, 'color15': color15})
    for index, key in enumerate(HUE_KEYS, start=9):
        value, changed = ensure_contrast(_emphasize(_require(palette, key), background), background, 3.0)
        colors['color%d' % index] = value
        adjusted = adjusted or changed
    text_out = HEADER + '\n' + ''.join('%s %s\n' % (key, colors[key]) for key in ORDER)
    return {'text': text_out, 'adjusted': adjusted, 'colors': colors}


def render_kitty(palette: dict) -> str:
    return render_details(palette)['text']
